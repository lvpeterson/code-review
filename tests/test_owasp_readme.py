"""The per-language OWASP coverage table in the root README matches RULES and
the source inventory (generated by tests/owasp_inventory.coverage_rows)."""
from __future__ import annotations

from pathlib import Path

import owasp_inventory as inv
from core import owasp_web
from core.owasp_web import RULES

README = Path(__file__).resolve().parent.parent / "README.md"


def readme_table(text: str) -> list[str]:
    start = text.index("<!-- owasp-coverage:start -->")
    end = text.index("<!-- owasp-coverage:end -->")
    return [ln for ln in text[start:end].splitlines() if ln.startswith("|")]


def test_readme_coverage_table_matches_rules():
    expected = inv.TABLE_HEADER.splitlines() + inv.coverage_rows(RULES)
    assert readme_table(README.read_text(encoding="utf-8")) == expected


def test_table_detects_a_changed_mapping(monkeypatch):
    # Remapping the only A03 supply-chain rule of the sca family must change the table.
    before = inv.coverage_rows(RULES)
    changed = dict(RULES)
    changed["SCA-001"] = ("A02",) + RULES["SCA-001"][1:]
    monkeypatch.setattr(owasp_web, "RULES", changed)
    after = inv.coverage_rows(changed)
    assert before != after
    assert any(row.startswith("| sca |") and "| A02 |" in row for row in after)


def test_every_family_has_rules():
    rows = inv.coverage_rows(RULES)
    assert [r.split("|")[1].strip() for r in rows] == inv.FAMILIES
    assert all(int(r.split("|")[2]) > 0 for r in rows)
